import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import process from 'node:process';
import { EventEmitter } from 'node:events';
import { createRequire } from 'node:module';
import { migrateUserAccess } from '../config/access-migration.js';
import { defaultPermissions, can } from '../shared/permissions.js';

process.env.APP_JS_DB_PATH = ':memory:';
const { getDbConnection } = await import('../config/db.js');
const Product = await import('../models/Product.js');
const Order = await import('../models/Order.js');
const { createAccessControl } = createRequire(import.meta.url)('../electron/access-control.cjs');
const { registerPaymentHandlers } = createRequire(import.meta.url)('../electron/payment-handlers.cjs');

test('main-process sessions enforce permissions, cashier identity, cost privacy and owner protection', async t => {
    const db = await getDbConnection();
    t.after(() => db.close());
    await db.exec(await fs.readFile(new URL('../database.sql', import.meta.url), 'utf8'));
    await db.run("UPDATE users SET role='Admin' WHERE id=1");
    await migrateUserAccess(db);
    await migrateUserAccess(db);
    assert.equal((await db.get('SELECT role FROM users WHERE id=1')).role,'Super Admin');
    const handlers = new Map();
    const raw = { handle(channel, handler) { assert.equal(handlers.has(channel), false); handlers.set(channel,handler); } };
    const { ipcMain } = createAccessControl(raw);
    registerPaymentHandlers(ipcMain);
    ipcMain.handle('get-products', () => Product.getAll());
    ipcMain.handle('get-order-detail', (_event,id) => Order.getOrderItems(id));
    ipcMain.handle('update-product', async (_event,id,data) => { await Product.update(id,data); return true; });
    let privilegedCalls = 0;
    for (const channel of ['get-expiry-batches','set-batch-expiry','remove-batch-stock','backup-database','restore-database','get-sales-profit-report','get-dashboard-data','get-finance-summary','store-expenditure','save-settings','create-stock-receipt','create-category','future-unknown-command']) {
        ipcMain.handle(channel, () => { privilegedCalls++; return {success:true}; });
    }
    const event = id => ({ sender: Object.assign(new EventEmitter(), {id}) });
    const owner = event(1), cashier = event(2), stranger = event(3);
    const invoke = (sender, channel, ...args) => handlers.get(channel)(sender,...args);
    await assert.rejects(invoke(stranger,'get-products'), /Sesi/);
    assert.equal((await invoke(owner,'auth-login',{username:'admin',password:'wrong'})).success,false);
    assert.equal((await invoke(owner,'auth-login',{username:'admin',password:'admin'})).success,true);
    assert.match((await db.get('SELECT password FROM users WHERE id=1')).password,/^\$2b\$/);
    const result = await invoke(owner,'save-user',{name:'Kasir Baru',username:'kasir',password:'kasir123',role:'Kasir',permissions:defaultPermissions('Kasir'),active:1});
    assert.equal(result.success,true);
    const cashierId=result.result;
    const listed = await invoke(owner,'get-users');
    assert.equal(listed.some(row => 'password' in row),false);
    const cashProfile=listed.find(row => row.id===cashierId);
    assert.equal(can(cashProfile,'reports.view'),false);
    assert.equal((await invoke(cashier,'auth-login',{username:'kasir',password:'kasir123'})).success,true);
    assert.equal(await invoke(stranger,'check-auth'),null);
    for (const channel of ['get-expiry-batches','set-batch-expiry','remove-batch-stock','get-users','save-user','backup-database','restore-database','get-sales-profit-report','get-dashboard-data','get-finance-summary','store-expenditure','save-settings','create-stock-receipt','create-category','future-unknown-command']) await assert.rejects(invoke(cashier,channel,{}),/hak akses|tidak diizinkan/);
    assert.equal(privilegedCalls,0);
    for(const channel of ['create-variant-barcode','preview-product-barcode','save-product-barcode','get-barcode-settings','save-barcode-settings','preview-barcode-settings']){
        ipcMain.handle(channel,()=>{throw new Error('Should not execute');});
        await assert.rejects(invoke(cashier,channel,{}),/hak akses/);
    }
    const product = await Product.create({name:'Rahasia Modal',price:10000,purchase_price:4000,stock:10});
    const variants = await Product.create({name:'Varian',variants:[{name:'A',price:10000,purchase_price:5000,stock:2}]});
    const catalog=await invoke(cashier,'get-products');
    assert.equal('purchase_price' in catalog[0],false);
    assert.equal('purchase_price' in catalog.find(row=>row.id===variants.lastID).variants[0],false);
    assert.equal((await Product.getById(product.lastID)).purchase_price,4000);
    const orderData = {userId:1,customerName:'Pembeli',items:[{product_id:product.lastID,qty:1,price:10000}],discount:0,amountPaid:0};
    await assert.rejects(invoke(cashier,'create-order',{...orderData,discount:1000}),/diskon/);
    const orderId = await invoke(cashier,'create-order',orderData);
    assert.equal((await Order.getOrderById(orderId)).user_id,cashierId);
    assert.equal('purchase_price' in (await invoke(cashier,'get-order-detail',orderId))[0],false);
    assert.equal((await invoke(cashier,'process-payment',{id:orderId,userId:1,total:1000,paymentMethod:'Cash'})).success,true);
    assert.equal((await db.get('SELECT user_id FROM payments WHERE order_id=?',[orderId])).user_id,cashierId);
    const permissions=[...defaultPermissions('Kasir'),'sales.discount','products.manage'];
    assert.equal((await invoke(owner,'save-user',{...cashProfile,permissions})).success,true);
    const discountOrder=await invoke(cashier,'create-order',{...orderData,discount:1000});
    assert.equal((await Order.getOrderById(discountOrder)).total_amount,9000);
    const existing=await Product.getById(product.lastID);
    await invoke(cashier,'update-product',product.lastID,{...existing,purchase_price:1,price:11000});
    assert.equal((await Product.getById(product.lastID)).purchase_price,4000);
    const selfOwner=listed.find(row=>row.id===1);
    assert.equal((await invoke(owner,'save-user',{...selfOwner,active:0})).success,false);
    assert.equal((await invoke(owner,'save-user',{...selfOwner,role:'Admin',permissions:null})).success,false);
    assert.equal((await invoke(owner,'save-user',{...cashProfile,permissions:['users.manage']})).success,false);
    assert.equal((await invoke(owner,'save-user',{...cashProfile,username:'ADMIN'})).success,false);
    assert.equal((await invoke(owner,'save-user',{...cashProfile,active:0})).success,true);
    assert.ok((await invoke(owner,'get-users')).find(row=>row.id===cashierId).permissions.includes('sales.create'));
    assert.equal(await invoke(cashier,'check-auth'),null);
    await assert.rejects(invoke(cashier,'get-products'),/Sesi/);
    assert.equal((await invoke(cashier,'auth-login',{username:'kasir',password:'kasir123'})).success,false);
    await invoke(owner,'save-user',{...cashProfile,active:1});
    await invoke(cashier,'auth-login',{username:'kasir',password:'kasir123'});
    await invoke(cashier,'auth-logout');
    assert.equal(await invoke(cashier,'check-auth'),null);
    await invoke(cashier,'auth-login',{username:'kasir',password:'kasir123'});
    await invoke(owner,'save-user',{...cashProfile,password:'reset123'});
    assert.equal(await invoke(cashier,'check-auth'),null);
    assert.equal((await invoke(cashier,'auth-login',{username:'kasir',password:'kasir123'})).success,false);
    assert.equal((await invoke(cashier,'auth-login',{username:'kasir',password:'reset123'})).success,true);
    await invoke(owner,'restore-database');
    assert.equal(await invoke(cashier,'check-auth'),null);
    assert.equal(await invoke(owner,'check-auth'),null);
    await invoke(owner,'auth-login',{username:'admin',password:'admin'});
    await assert.rejects(invoke(owner,'future-unknown-command'),/tidak diizinkan/);
    const second = await invoke(owner,'save-user',{name:'Pemilik 2',username:'owner2',password:'owner123',role:'Super Admin',active:1});
    const attempts=await Promise.all([invoke(owner,'save-user',{...selfOwner,active:0}),invoke(owner,'save-user',{id:second.result,name:'Pemilik 2',username:'owner2',role:'Super Admin',active:0})]);
    assert.equal(attempts.filter(item=>item.success).length,1);
    assert.equal((await db.get("SELECT COUNT(*) as count FROM users WHERE role='Super Admin' AND active=1")).count,1);
});
