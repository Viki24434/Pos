import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import process from 'node:process';

process.env.APP_JS_DB_PATH = ':memory:';
const { getDbConnection } = await import('../config/db.js');
const Product = await import('../models/Product.js');
const Customer = await import('../models/Customer.js');
const Order = await import('../models/Order.js');
const { getReceivables, setDueDate } = await import('../models/Receivable.js');

test('receivables list uses real balances, filters, due dates and installments', async t => {
    const db = await getDbConnection();
    t.after(() => db.close());
    await db.exec(await fs.readFile(new URL('../database.sql', import.meta.url), 'utf8'));
    const product = await Product.create({ name: 'Sabun', price: 10000, stock: 20 });
    const customer = await Customer.addCustomer({ name: 'Budi %_', phone: '08123456', status: 'Umum' });
    const create = (name, qty, customerId = 0) => Order.createOrder(name, [{ product_id: product.lastID, qty, price: 10000 }], 0, 0, customerId);
    const unpaid = await create('Budi', 1, customer.lastID);
    const partial = await create('Sari', 3);
    const paid = await create('Lunas', 1);
    const cancelled = await create('Batal', 2);
    await Order.addPayment(partial, 1, 'Transfer', 5000);
    await Order.addPayment(paid, 1, 'Cash', 10000);
    await db.run("UPDATE orders SET status='Dibatalkan' WHERE id=?", [cancelled]);
    await db.run("UPDATE orders SET payment_status='Lunas', status=NULL WHERE id=?", [unpaid]);
    await db.run("INSERT INTO stores (id,name) VALUES (2,'Toko Lain')");
    await db.run("INSERT INTO orders (store_id,customer_id,invoice_number,customer_name,total_amount) VALUES (2,0,'OTHER','Toko Lain',10000), (1,0,'ZERO','Nol',0)");
    let result = await getReceivables();
    assert.deepEqual(result.rows.map(row => row.id).sort((a,b) => a-b), [unpaid, partial]);
    assert.equal(result.summary.remaining, 35000);
    assert.equal(result.summary.invoices, 2);
    assert.equal(result.rows.find(row => row.id === unpaid).debt_status, 'Belum Bayar');
    assert.equal(result.rows.find(row => row.id === partial).remaining, 25000);
    assert.equal((await getReceivables({ status: 'partial' })).rows[0].id, partial);
    assert.equal((await getReceivables({ status: 'unpaid' })).rows[0].id, unpaid);
    for (const search of ['08123456', 'Budi', '%_', (await Order.getOrderById(unpaid)).invoice_number]) assert.equal((await getReceivables({ search })).rows[0].id, unpaid);
    assert.equal((await getReceivables({ search: 'Tidak Ada' })).summary.invoices, 0);
    await assert.rejects(getReceivables({ status: 'invalid' }), /Filter/);
    const { today, yesterday } = await db.get("SELECT DATE('now','localtime') as today, DATE('now','localtime','-1 day') as yesterday");
    await setDueDate(unpaid, yesterday);
    await setDueDate(partial, today);
    result = await getReceivables();
    assert.equal(result.rows[0].id, unpaid);
    assert.equal(result.summary.overdue, 1);
    assert.equal(result.summary.overdue_amount, 10000);
    assert.equal((await getReceivables({ due: 'overdue' })).summary.invoices, 1);
    assert.equal((await getReceivables({ due: 'undated' })).summary.invoices, 0);
    await setDueDate(partial, '');
    assert.equal((await getReceivables({ due: 'undated' })).rows[0].id, partial);
    for (const date of ['2026-02-30', 'not-a-date', '2026-1-1']) await assert.rejects(setDueDate(unpaid, date), /Tanggal/);
    for (const id of [paid, cancelled, 99999]) await assert.rejects(setDueDate(id, today), /tidak ditemukan|lunas/);
    await assert.rejects(Order.addPayment(cancelled, 1, 'Cash', 1000), /dibatalkan/);
    await Order.addPayment(unpaid, 1, 'Cash', 3000);
    assert.equal((await getReceivables({ search: 'Budi' })).rows[0].remaining, 7000);
    assert.equal((await getReceivables({ search: 'Budi' })).rows[0].debt_status, 'DP');
    await Order.addPayment(unpaid, 1, 'Transfer', 7000);
    assert.equal((await getReceivables({ search: 'Budi' })).rows.length, 0);
    assert.equal((await Order.getOrderPayments(unpaid)).length, 2);
    await Order.addPayment(partial, 1, 'Cash', 25000);
    assert.deepEqual((await getReceivables()).summary, { remaining: 0, invoices: 0, overdue: 0, overdue_amount: 0 });
});
