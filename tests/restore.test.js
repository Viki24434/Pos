import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import {open} from 'sqlite';
import sqlite3 from 'sqlite3';
const directory=await fs.mkdtemp(path.join(os.tmpdir(),'app-js-restore-test-'));
process.env.APP_JS_DB_PATH=path.join(directory,'active.sqlite');
const {getDbConnection}=await import('../config/db.js');
const {createBackup,restoreBackup,inspectBackup}=await import('../models/Backup.js');
test('restore validates backups, preserves a recovery copy and migrates old data',async t=>{
 const db=await getDbConnection();
 t.after(async()=>{await db.close();for(const name of await fs.readdir(directory))await fs.unlink(path.join(directory,name));await fs.rmdir(directory);});
 await db.exec(await fs.readFile(new URL('../database.sql',import.meta.url),'utf8'));
 await db.exec('PRAGMA journal_mode=WAL');
 await db.run("INSERT INTO customers(store_id,name,status) VALUES(1,'VIP dari backup','VIP')");
 const backup=path.join(directory,'backup.sqlite');
 await createBackup(backup);
 await db.run("UPDATE customers SET name='Data terbaru'");
 const invalid=path.join(directory,'invalid.sqlite');await fs.writeFile(invalid,'invalid database');
 await assert.rejects(inspectBackup(invalid));
 await assert.rejects(restoreBackup(invalid,directory));
 assert.equal((await db.get('SELECT name FROM customers')).name,'Data terbaru');
 const restored=await restoreBackup(backup,directory);
 assert.equal((await db.get('SELECT name FROM customers')).name,'VIP dari backup');
 const recovery=await open({filename:restored.safetyPath,driver:sqlite3.Database,mode:sqlite3.OPEN_READONLY});
 assert.equal((await recovery.get('SELECT name FROM customers')).name,'Data terbaru');await recovery.close();
 assert.equal((await db.get('PRAGMA quick_check')).quick_check,'ok');
 await db.run("INSERT INTO customers(store_id,name,status) VALUES(1,'Sesudah restore','Umum')");
 assert.equal((await db.get('SELECT COUNT(*) as count FROM customers')).count,2);
 await assert.rejects(restoreBackup(process.env.APP_JS_DB_PATH,directory),/sedang digunakan/);
});
